type DatabaseError = { code?: string; message?: string; details?: string | null };

function isDatabaseError(reason: unknown): reason is DatabaseError {
  return typeof reason === "object" && reason !== null && typeof (reason as DatabaseError).code === "string";
}

/** True when a message was generated by PostgreSQL rather than raised by our own functions. */
function looksGenerated(message: string) {
  return /violates|relation "|column "|constraint "|syntax|invalid input|permission denied|row-level security/i.test(message);
}

function constraintName(error: DatabaseError) {
  const text = `${error.message ?? ""} ${error.details ?? ""}`;
  return /constraint "([a-z0-9_]+)"/i.exec(text)?.[1];
}

export function databaseFailure(error: DatabaseError, fallback: string): ActionFailure {
  const name = constraintName(error);
  if (name && constraintMessages[name]) return failure(constraintMessages[name].code, constraintMessages[name].message);
  const message = error.message ?? "";
  const ownMessage = message && !looksGenerated(message) ? message.trim() : "";
  switch (error.code) {
    case "23505": return failure("DUPLICATE_RECORD", "A matching record already exists. Reload the page to see it.");
    case "23P01": return failure("CONFLICT", ownMessage ? withPeriod(ownMessage) : "This conflicts with an existing record for the same dates.");
    case "23514": return failure("RULE_VIOLATION", ownMessage ? withPeriod(ownMessage) : fallback);
    case "23503": return failure("LINKED_RECORD", ownMessage ? withPeriod(ownMessage) : "A linked unit, driver or record is missing or was archived. Reload the page and try again.");
    case "23502": return failure("INVALID_INPUT", "A required field is empty. Fill in every required field.");
    case "22P02":
    case "22007":
    case "22008": return failure("INVALID_INPUT", "One of the values is not in the expected format. Check the dates and numbers.");
    case "42501": return failure("FORBIDDEN", ownMessage ? withPeriod(ownMessage) : "You do not have permission to do that. Ask the owner if you need this change.");
    case "P0002": return failure("NOT_FOUND", ownMessage ? `${withPeriod(ownMessage)} Reload the page and try again.` : "This record was not found. Reload the page and try again.");
    case "22023": return failure("INVALID_INPUT", ownMessage ? withPeriod(ownMessage) : fallback);
    case "PGRST116": return failure("NOT_FOUND", "This record was not found or you cannot change it. Reload the page and try again.");
    default: return failure("UNEXPECTED", fallback);
  }
}

function withPeriod(message: string) { return /[.!?]$/.test(message) ? message : `${message}.`; }

/**
 * Turns a Zod error into one sentence. Custom (refine) messages are already plain language;
 * other issues name the fields to check using the action's labels.
 */
export function validationFailure(error: ZodError, labels: Record<string, string> = {}): ActionFailure {
  const fieldErrors: Record<string, string[]> = {};
  const custom: string[] = [];
  const fields: string[] = [];
  for (const issue of error.issues) {
    const key = String(issue.path[0] ?? "");
    if (key) (fieldErrors[key] ??= []).push(issue.message);
    if (issue.code === "custom") { if (!custom.includes(issue.message)) custom.push(issue.message); continue; }
    const label = labels[key];
    if (label && !fields.includes(label)) fields.push(label);
  }
  const parts = [...custom.map(withPeriod)];
  if (fields.length) parts.push(`Check the ${joinLabels(fields)}.`);
  const message = parts.length ? parts.join(" ") : "Some details are missing or invalid. Check the form and try again.";
  return failure("INVALID_INPUT", message, Object.keys(fieldErrors).length ? fieldErrors : undefined);
}

function joinLabels(labels: string[]) {
  if (labels.length < 3) return labels.join(" and ");
  return `${labels.slice(0, -1).join(", ")} and ${labels[labels.length - 1]}`;
}

export function toActionFailure(reason: unknown, fallback: string, labels?: Record<string, string>): ActionFailure {
  if (reason instanceof ActionError) return failure(reason.code, reason.message);
  if (reason instanceof ZodError) return validationFailure(reason, labels);
  if (isDatabaseError(reason)) return databaseFailure(reason, fallback);
  return failure("UNEXPECTED", fallback);
}

/**
 * Runs an action body and returns a result. Next.js control-flow errors (redirect, notFound)
 * are rethrown by the caller-provided `rethrow` (next/navigation's unstable_rethrow); it is
 * passed in so this module stays free of Next.js imports and easy to unit test.
 */
export async function runAction<T>(
  options: { fallback: string; labels?: Record<string, string>; rethrow?: (reason: unknown) => void; successMessage?: string },
  body: () => Promise<T>,
): Promise<ActionResult<T>> {
  try {
    return success(await body(), options.successMessage);
  } catch (reason) {
    options.rethrow?.(reason);
    if (!(reason instanceof ActionError) && !(reason instanceof ZodError)) console.error("Action failed", reason);
    return toActionFailure(reason, options.fallback, options.labels);
  }
}
